SITEMAP_TEMPLATE = """<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
%%URLS%%</urlset>
"""

SITEMAP_URL = """   <url>
      <loc>%%LOC%%</loc>
   </url>
"""


# ---------------------------------------------------------------------------
# Generation functions
# ---------------------------------------------------------------------------

def generate_model_page(model):
    """Generate HTML for an individual model page."""
    html = MODEL_PAGE_TEMPLATE
    html = html.replace("%%GENERATED_COMMENT%%", GENERATED_COMMENT)
    html = html.replace("%%SITE_URL%%", SITE_URL)
    html = html.replace("%%TITLE%%", model["title"])
    html = html.replace("%%SLUG%%", model["slug"])
    html = html.replace("%%META_DESCRIPTION%%", escape_for_html_attr(model.get("meta_description", model["tagline"])))
    html = html.replace("%%THUMBNAIL%%", model["thumbnail"])
    html = html.replace("%%SECTIONS_HTML%%", render_sections(model.get("sections", [])))
    html = html.replace("%%MEDIA_NAV%%", render_media_nav(model.get("media", [])))
    html = html.replace("%%MEDIA_JSON%%", json.dumps(model.get("media", []), indent=8))
    return html


def generate_grid_page(models):
    """Generate the models grid HTML page."""
    boxes = []
    for model in models:
        box = MODEL_BOX_TEMPLATE
        box = box.replace("%%SLUG%%", model["slug"])
        box = box.replace("%%TAGLINE_ATTR%%", escape_for_html_attr(model["tagline"]))
        box = box.replace("%%THUMBNAIL%%", model["thumbnail"])
        box = box.replace("%%TITLE_ATTR%%", escape_for_html_attr(model["title"]))
        box = box.replace("%%HOVER_TEXT%%", model["hover_text"])
        boxes.append(box)

    html = MODELS_GRID_TEMPLATE
    html = html.replace("%%GENERATED_COMMENT%%", GENERATED_COMMENT)
    html = html.replace("%%SITE_URL%%", SITE_URL)
    html = html.replace("%%MODEL_BOXES%%", "\n".join(boxes))
    return html


def generate_sitemap(models):
    """Generate sitemap.xml with all pages."""
    urls = []
    # Static pages
    urls.append(SITEMAP_URL.replace("%%LOC%%", SITE_URL + "/"))
    urls.append(SITEMAP_URL.replace("%%LOC%%", SITE_URL + "/models.html"))
    # Model pages
    for model in models:
        loc = f"{SITE_URL}/models/{model['slug']}/"
        urls.append(SITEMAP_URL.replace("%%LOC%%", loc))
    return SITEMAP_TEMPLATE.replace("%%URLS%%", "".join(urls))


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    print("build-html.py — generating model pages, grid, and sitemap\n")

    # Load model data
    models = load_models()
    if not models:
        print("  WARNING: No model.json files found in models/*/")
        print("  Expected: models/{model-name}/model.json")
        return

    print(f"  Found {len(models)} models:")
    for m in models:
        print(f"    [{m.get('sort_order', '?')}] {m['slug']}: {m['title']}")

    # Generate individual model pages
    print(f"\n  Generating model pages in {MODELS_OUTPUT_DIR}/...")
    for model in models:
        out_dir = os.path.join(MODELS_OUTPUT_DIR, model["slug"])
        os.makedirs(out_dir, exist_ok=True)
        out_path = os.path.join(out_dir, "index.html")
        html = generate_model_page(model)
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(html)
        print(f"    ✓ {out_path}")

    # Generate grid page
    print("\n  Generating models.html...")
    grid_html = generate_grid_page(models)
    with open(GRID_OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(grid_html)
    print(f"    ✓ {GRID_OUTPUT_PATH}")

    # Generate sitemap
    print("\n  Generating sitemap.xml...")
    sitemap = generate_sitemap(models)
    with open(SITEMAP_OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(sitemap)
    print(f"    ✓ {SITEMAP_OUTPUT_PATH}")

    print(f"\n  Done! Generated {len(models)} model pages + grid + sitemap.")


if __name__ == "__main__":
    main()
