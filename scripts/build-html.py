#!/usr/bin/env python3
"""
build-html.py

Generates:
  - Individual model pages at models/{slug}/index.html
  - Models grid page at models.html
  - Sitemap at sitemap.xml

Usage:
  python build-html.py

Zero dependencies — uses only Python standard library.
"""

import os
import json
import glob
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent if SCRIPT_DIR.name == "scripts" else SCRIPT_DIR

SITE_URL = "https://juke32.com"
MODELS_DATA_DIR = str(REPO_ROOT / "models")
MODELS_OUTPUT_DIR = str(REPO_ROOT / "models")
GRID_OUTPUT_PATH = str(REPO_ROOT / "models.html")
SITEMAP_OUTPUT_PATH = str(REPO_ROOT / "sitemap.xml")
GENERATED_COMMENT = "<!-- GENERATED BY build-html.py — DO NOT EDIT -->"


# ---------------------------------------------------------------------------
# Data loading
# ---------------------------------------------------------------------------

def load_models():
    """Scan models/*/model.json and return list sorted by sort_order (excluding sort_order 0)."""
    models = []
    pattern = os.path.join(MODELS_DATA_DIR, "*", "model.json")
    for json_path in glob.glob(pattern):
        dir_name = os.path.basename(os.path.dirname(json_path))
        if dir_name.startswith("_"):  # Skip _template
            continue
        with open(json_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        if data.get("sort_order", 0) <= 0:
            # Clean up index.html if it was previously generated for a 0 sort_order model
            idx_file = os.path.join(os.path.dirname(json_path), "index.html")
            if os.path.exists(idx_file):
                os.remove(idx_file)
            continue
        models.append(data)
    models.sort(key=lambda m: m.get("sort_order", 0), reverse=True)
    return models


# ---------------------------------------------------------------------------
# HTML rendering helpers
# ---------------------------------------------------------------------------

def render_sections(sections):
    """Convert sections list to HTML string."""
    parts = []
    for section in sections:
        heading = section.get("heading", "")
        if heading:
            parts.append(f"                    <h3>{heading}</h3>")

        if section["type"] == "text":
            content = section.get("content", "")
            for para in content.split("\n"):
                para = para.strip()
                if para:
                    parts.append(f"                    <p>{para}</p>")

        elif section["type"] == "list":
            parts.append("                    <ul>")
            for item in section.get("items", []):
                parts.append(f"                        <li>{item}</li>")
            parts.append("                    </ul>")

    return "\n".join(parts)


def render_media_nav(media):
    """Render prev/next nav buttons if multiple media items."""
    if len(media) <= 1:
        return ""
    return """                    <div class="nav-btn-container">
                        <button class="nav-btn prev">&lt;</button>
                        <button class="nav-btn next">&gt;</button>
                    </div>"""


def escape_for_html_attr(text):
    """Escape text for use in HTML attributes."""
    return text.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;").replace(">", "&gt;")


